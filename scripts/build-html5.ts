/**
 * Builds the self-contained offline HTML5 portal package (plan option A).
 *   npx tsx scripts/build-html5.ts [--variant base|ng|y8]   (default: builds base + ng)
 * - Generates html5/generated/catalog.ts (with correctChoice) from src/server/levels/spec.ts. That file is
 *   gitignored and only imported by the html5/ entry; the Next app's server-only boundary is unchanged.
 * - Vite build -> dist-html5/<variant>/, copies level PNGs, writes README.txt, scans for external URLs,
 *   zips spot-the-difference-html5-v1[-variant].zip with index.html at the zip root.
 */
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { LEVELS_V1 } from "../src/server/levels/spec";

const ROOT = process.cwd();
const OUT = join(ROOT, "dist-html5");
const sha = execFileSync("git", ["rev-parse", "--short", "HEAD"]).toString().trim();
const VERSION = `HTML5 build v1 · levelSet v1 · sim-v2 · from spotthedifferencegame.com · ${sha}`;
const argVariant = process.argv.includes("--variant") ? process.argv[process.argv.indexOf("--variant") + 1] : null;
const variants = argVariant ? [argVariant] : ["base", "ng"];
const NO_LINK = new Set(["ng", "y8"]);

mkdirSync(join(ROOT, "html5/generated"), { recursive: true });
const catalog = LEVELS_V1.map((l) => ({
  level: l.level,
  gridSize: l.gridSize,
  limitMs: l.limitMs,
  correctChoice: l.correctChoice,
  choices: l.choices,
  imageUrl: `assets/levels/v1/${String(l.level).padStart(2, "0")}.png`,
}));
writeFileSync(
  join(ROOT, "html5/generated/catalog.ts"),
  `// GENERATED by scripts/build-html5.ts from src/server/levels/spec.ts — HTML5 package only, do not import from src/.\n` +
    `import type { GridSize } from "@/game/contracts";\n` +
    `export interface Html5Level { level: number; gridSize: GridSize; limitMs: number; correctChoice: string; choices: string[]; imageUrl: string }\n` +
    `export const HTML5_LEVELS: Html5Level[] = ${JSON.stringify(catalog)};\n`,
);

const walk = (dir: string): string[] => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]));

rmSync(OUT, { recursive: true, force: true });
for (const variant of variants) {
  const out = join(OUT, variant);
  execFileSync("npx", ["vite", "build", "--config", "html5/vite.config.ts", "--logLevel", "warn"], {
    stdio: "inherit",
    env: { ...process.env, HTML5_VARIANT: variant, HTML5_OUT: out, HTML5_VERSION: VERSION },
  });
  // Classic script so index.html also runs from file:// (module scripts are CORS-blocked there). The bundle is a
  // single chunk with no imports/exports, so dropping type="module" is safe; guarded below.
  const htmlPath = join(out, "index.html");
  const html = readFileSync(htmlPath, "utf8")
    .replace(/<script type="module" crossorigin src="([^"]+)"><\/script>/, '<script defer src="$1"></script>')
    .replace(/ crossorigin/g, "");
  if (/type="module"/.test(html)) throw new Error("index.html still has a module script");
  writeFileSync(htmlPath, html);
  for (const js of walk(join(out, "assets")).filter((f) => f.endsWith(".js"))) {
    if (/^\s*(import|export)\s/m.test(readFileSync(js, "utf8")) || /import\.meta/.test(readFileSync(js, "utf8"))) throw new Error(`${js} is not a self-contained script`);
  }
  cpSync(join(ROOT, "public/levels/v1"), join(out, "assets/levels/v1"), { recursive: true });
  for (const f of readdirSync(join(ROOT, "src/styles/fonts")).filter((f) => f.startsWith("LICENSE"))) cpSync(join(ROOT, "src/styles/fonts", f), join(out, "assets/fonts-licenses", f));
  if (NO_LINK.has(variant)) {
    // Zero http(s) strings in no-link builds. These are inert text (React's error-decoder prefix, Tailwind's banner
    // comment, URLs inside the OFL licence files), never rendered as links or fetched; keep the text, drop the scheme.
    for (const file of walk(out).filter((f) => /\.(js|css|txt)$/.test(f))) {
      writeFileSync(file, readFileSync(file, "utf8").replace(/https?:\/\/(?!www\.w3\.org\/)/g, ""));
    }
  }
  writeFileSync(
    join(out, "README.txt"),
    `Spot the Difference: Human vs AI — portal edition (${variant})\n${VERSION}\n\n` +
      `Self-contained offline build: 20 levels vs a simulated AI, 3 chances, progress saved in localStorage.\n` +
      `No network requests, no accounts, no analytics. Level art is generated in-house from SVG paths.\n` +
      `Fonts: Fusion Pixel, Press Start 2P, JetBrains Mono (SIL OFL, see assets/fonts-licenses/).\n`,
  );

  // Scan: no http(s) URLs / window.open / /api in no-link variants; no secrets anywhere.
  const files = walk(out);
  let bytes = 0;
  const problems: string[] = [];
  for (const file of files) {
    bytes += statSync(file).size;
    if (!/\.(html|js|css|txt|json)$/.test(file)) continue;
    const text = readFileSync(file, "utf8");
    const rel = relative(out, file);
    if (/\.env|sk-[A-Za-z0-9]{20}|OPENAI|workers\.dev|SIM_SEED_SECRET/.test(text)) problems.push(`${rel}: secret-like token`);
    if (/["'`]\/api\//.test(text)) problems.push(`${rel}: /api reference`);
    if (NO_LINK.has(variant)) {
      const urls = text.match(/https?:\/\/[^\s"'`)<>]+/g) ?? [];
      // XML/SVG namespace identifiers are not links or requests.
      const external = urls.filter((u) => !/^http:\/\/www\.w3\.org\//.test(u));
      if (external.length) problems.push(`${rel}: URLs ${[...new Set(external)].slice(0, 5).join(", ")}`);
      if (/window\.open|\.open\(\s*["'`]http/.test(text)) problems.push(`${rel}: window.open`);
      if (/<a\s[^>]*href=["']http/.test(text)) problems.push(`${rel}: external <a>`);
    }
  }
  if (bytes > 5 * 1024 * 1024) problems.push(`size ${bytes} > 5MB`);
  if (problems.length) {
    console.error(`[html5:${variant}] scan failed:\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  const zipName = variant === "ng" ? "spot-the-difference-html5-v1.zip" : `spot-the-difference-html5-v1-${variant}.zip`;
  rmSync(join(OUT, zipName), { force: true });
  // Python's zipfile is available everywhere `zip` may not be; entries are relative so index.html sits at the root.
  execFileSync("python3", ["-c", "import shutil,sys; shutil.make_archive(sys.argv[1], 'zip', sys.argv[2])", join(OUT, zipName.replace(/\.zip$/, "")), out]);
  console.log(`[html5:${variant}] ok · ${files.length} files · ${(bytes / 1024).toFixed(0)} KB uncompressed · ${zipName}`);
}
