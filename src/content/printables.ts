export const sheetPuzzles = (sheet: SheetSpec): QuickPuzzle[] =>
  sheet.grids.map((grid, i) => makePuzzle(`print-${sheet.id}-${i}`, { theme: sheet.theme, grid, changes: sheet.changes }));

export const cellName = (index: number, grid: number) => `row ${Math.floor(index / grid) + 1}, column ${(index % grid) + 1}`;

/** Answer key lines, e.g. "Puzzle 1: row 2, column 3 (3 pixels changed)". */
export const answerLines = (sheet: SheetSpec): string[] =>
  sheetPuzzles(sheet).map((p, i) => `Puzzle ${i + 1}: ${cellName(p.oddIndex, p.grid)} (${p.changed.length} ${p.changed.length === 1 ? "pixel" : "pixels"} changed)`);
