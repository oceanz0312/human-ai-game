/**
 * Printable sheets (/printable). Shared by the page, the PDF generator (scripts/generate-printables.ts) and tests,
 * so the web sheet, the downloadable PDF and its answer key are always the same seeded puzzles.
 */
export interface SheetSpec {
  /** Anchor id (/printable#<id>). */
  id: string;
  /** Visible H2. */
  title: string;
  /** Short label for the in-page table of contents. */
  toc: string;
  theme: QuickTheme;
  grids: number[];
  changes: number;
  /** Static PDF downloads (public/printables/, generated by `npm run printables:generate`). */
  pdf?: { sheet: string; answers: string };
}

